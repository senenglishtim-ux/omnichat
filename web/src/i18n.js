let lang = (() => {
  try { const s = localStorage.getItem('omnichat_lang'); if (s) return s; } catch { /* ignore */ }
  const q = new URLSearchParams(window.location.search).get('lang');
  if (q) return q;
  return (navigator.language || 'en').toLowerCase().startsWith('ru') ? 'ru' : 'en';
})();

export const getLang = () => lang;
export function setLang(l) { lang = l; try { localStorage.setItem('omnichat_lang', l); } catch { /* ignore */ } window.location.reload(); }
export const locale = () => (lang === 'ru' ? 'ru-RU' : 'en-GB');

export function t(key, vars) {
  const e = dict[key];
  let s = e ? e[lang === 'ru' ? 0 : 1] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
